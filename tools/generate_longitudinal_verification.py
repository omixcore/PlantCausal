"""Generate a synthetic longitudinal package and independent statsmodels IPW reference.
Run with Python, numpy, scipy and statsmodels. No biological observations are used.
"""
from verification_metadata import standardize
from pathlib import Path
import json,csv,shutil
import numpy as np
import statsmodels.api as sm
from scipy.special import expit
root=Path(__file__).resolve().parents[1]
rng=np.random.default_rng(19127);n=500;k=3
z=rng.normal(size=n);l=np.zeros((n,k));a=np.zeros((n,k),dtype=int)
for step in range(k):
 l[:,step]=.35*z+(0 if step==0 else .25*a[:,step-1])+rng.normal(size=n)
 a[:,step]=rng.binomial(1,expit(-.1+.25*z+.35*l[:,step]+(0 if step==0 else .15*a[:,step-1])))
y=5+.8*a.sum(axis=1)+.5*l[:,-1]+.3*z+rng.normal(size=n)
r=rng.binomial(1,expit(2+.15*z-.15*l[:,-1]-.2*a[:,-1])).astype(bool)
weights=np.ones(n);probabilities=[];retentions=[]
for step in range(k):
 x=np.column_stack([np.ones(n),z,l[:,:step+1],a[:,:step]])
 e=sm.Logit(a[:,step],x).fit(disp=0).predict(x)
 observation=np.ones(n)
 if step==k-1:
  rx=np.column_stack([x,a[:,step]])
  observation=sm.Logit(r,rx).fit(disp=0).predict(rx)
 weights/=np.where(a[:,step]==1,e,1-e)*observation
 probabilities.append(e);retentions.append(observation)
regime_a=(a==1).all(axis=1)&r;regime_b=(a==0).all(axis=1)&r
reference=np.average(y[regime_a],weights=weights[regime_a])-np.average(y[regime_b],weights=weights[regime_b])
protocol=json.loads((root/'examples/linear_verification/protocol.json').read_text())
protocol.update(trial_id='SYNTHETIC_LONGITUDINAL_500',title='Synthetic longitudinal sustained-regime verification')
protocol['target_trial']['outcome']={'variable_id':'response','definition':'Generated continuous endpoint','time':90,'unit':'arbitrary'}
protocol['target_trial']['estimand'].update(strategy_effect='sustained_strategy',intercurrent_events='Loss to follow-up handled by explicitly selected IPCW')
protocol['target_trial']['analysis_plan']='Sequential inverse treatment/observation weighting, static A-A-A versus B-B-B, Hajek means; cluster bootstrap'
protocol['extensions']={'longitudinal':{'time_grid':[0,30,60,90]}}
protocol['provenance']['transformations']='Generated by tools/generate_longitudinal_verification.py, numpy seed19127; no observed biological data'
protocol['emulation']['design']='observational'
protocol['emulation']['analysis_mapping']='Use baseline_z and pre-decision time-varying history_l with MSM_IPW and IPCW'
protocol['emulation']['limitations']=['Synthetic verification only; point estimate is an independent sample reference, not a biological effect']
folder=root/'examples/longitudinal_verification';folder.mkdir(exist_ok=True)
protocol=standardize(protocol,'longitudinal',n)
(folder/'protocol.json').write_text(json.dumps(protocol,indent=2,ensure_ascii=False)+'\n')
names=['units.tsv','variables.tsv','observations.tsv','treatments.tsv','events.tsv']
headers={name:next(csv.reader((root/'examples/linear_verification'/name).open(),delimiter='\t')) for name in names};rows={name:[] for name in names}
rows['variables.tsv']=[['baseline_z','baseline_confounder','number','arbitrary','Generated baseline covariate','before_first_treatment','NA'],['history_l','time_varying_confounder','number','arbitrary','Generated pre-decision state','before_each_treatment','NA'],['response','outcome','number','arbitrary','Generated endpoint','day90','NA']]
for i in range(n):
 id=f'U{i+1:04d}';trial=protocol['trial_id'];arm='A' if a[i,0] else 'B'
 rows['units.tsv'].append([trial,id,'NA','plot',id,id,'NA','synthetic species','synthetic genotype','2026-01-01',1,arm,'SYNTHETIC'])
 rows['observations.tsv'].append([trial,id,-1,'baseline_z',z[i],'NA','NA','NA','SYNTHETIC','generated'])
 for step in range(k):
  rows['observations.tsv'].append([trial,id,step*30-1,'history_l',l[i,step],'NA','NA','NA','SYNTHETIC','generated'])
  rows['treatments.tsv'].append([trial,id,step*30,(step+1)*30,'A' if a[i,step] else 'B','synthetic actual strategy','NA','NA','adherent' if a[i,step]==a[i,0] else 'nonadherent','SYNTHETIC'])
  if step>0 and a[i,step]!=a[i,step-1]:rows['events.tsv'].append([trial,id,step*30,'strategy_switch','generated verified strategy change','SYNTHETIC'])
 rows['observations.tsv'].append([trial,id,90,'response',y[i] if r[i] else 'NA','NA' if r[i] else 'lost_to_followup','NA','NA','SYNTHETIC','generated'])
 if not r[i]:rows['events.tsv'].append([trial,id,90,'loss_to_followup','generated endpoint non-observation','SYNTHETIC'])
for name in names:
 with (folder/name).open('w',newline='') as f:
  writer=csv.writer(f,delimiter='\t',lineterminator='\n');writer.writerow(headers[name]);writer.writerows(rows[name])
shutil.copytree(folder,root/'src/main/resources/builtin/longitudinal_verification',dirs_exist_ok=True)
(root/'src/test/resources/longitudinal-statsmodels-reference.json').write_text(json.dumps({'effect':float(reference),'regimeA':int(regime_a.sum()),'regimeB':int(regime_b.sum())},indent=2)+'\n')
print('Independent statsmodels sustained-regime IPCW-IPW:',reference,'support:',regime_a.sum(),regime_b.sum())
