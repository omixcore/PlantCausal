"""Independent sequential censoring reference with losses at multiple grid boundaries."""
from verification_metadata import standardize
from pathlib import Path
import csv,json
import numpy as np,statsmodels.api as sm
from scipy.special import expit
root=Path(__file__).resolve().parents[1];rng=np.random.default_rng(7139);n=500;steps=3
z=rng.normal(size=n);l=np.zeros((n,steps));a=np.zeros((n,steps),dtype=int);retained=np.ones((n,steps),dtype=bool);risk=np.ones(n,dtype=bool);weights=np.ones(n);risk_at=[]
for k in range(steps):
 risk_at.append(risk.copy());l[:,k]=.3*z+(0 if k==0 else .2*a[:,k-1])+rng.normal(size=n)
 a[:,k]=rng.binomial(1,expit(-.1+.3*z+.3*l[:,k]+(0 if k==0 else .1*a[:,k-1])))
 retained[:,k]=risk & rng.binomial(1,expit(2.8+.1*z-.1*l[:,k]-.1*a[:,k])).astype(bool)
 x=np.column_stack([np.ones(n),z,l[:,:k+1],a[:,:k]])
 e=sm.Logit(a[risk,k],x[risk]).fit(disp=0).predict(x[risk]);rx=np.column_stack([x[risk],a[risk,k]])
 p=sm.Logit(retained[risk,k],rx).fit(disp=0).predict(rx)
 weights[risk]/=np.where(a[risk,k],e,1-e)*p;weights[~retained[:,k]]=0;risk=retained[:,k].copy()
y=5+.8*a.sum(axis=1)+.5*l[:,-1]+.3*z+rng.normal(size=n)
arm_a=(a==1).all(axis=1)&risk;arm_b=(a==0).all(axis=1)&risk
estimate=np.average(y[arm_a],weights=weights[arm_a])-np.average(y[arm_b],weights=weights[arm_b])
source=root/'examples/longitudinal_verification';dest=root/'src/test/resources/longitudinal_dropout';dest.mkdir(exist_ok=True)
protocol=json.loads((source/'protocol.json').read_text());protocol['trial_id']='SYNTHETIC_DROPOUT_500';protocol['provenance']['transformations']='Generated by tools/generate_dropout_verification.py, numpy seed7139, losses on multiple boundaries'
protocol=standardize(protocol,'dropout',n)
(dest/'protocol.json').write_text(json.dumps(protocol,ensure_ascii=False,indent=2)+'\n')
names=['units.tsv','variables.tsv','observations.tsv','treatments.tsv','events.tsv'];headers={name:next(csv.reader((source/name).open(),delimiter='\t')) for name in names};rows={name:[] for name in names}
rows['variables.tsv']=list(csv.reader((source/'variables.tsv').open(),delimiter='\t'))[1:]
for i in range(n):
 id=f'U{i+1:04d}';trial=protocol['trial_id'];arm='A' if a[i,0] else 'B'
 rows['units.tsv'].append([trial,id,'NA','plot',id,id,'NA','synthetic species','synthetic genotype','2026-01-01',1,arm,'SYNTHETIC'])
 rows['observations.tsv'].append([trial,id,-1,'baseline_z',z[i],'NA','NA','NA','SYNTHETIC','generated'])
 for k in range(steps):
  if not risk_at[k][i]:break
  rows['observations.tsv'].append([trial,id,k*30-1,'history_l',l[i,k],'NA','NA','NA','SYNTHETIC','generated'])
  rows['treatments.tsv'].append([trial,id,k*30,(k+1)*30,'A' if a[i,k] else 'B','actual generated strategy','NA','NA','adherent' if a[i,k]==a[i,0] else 'nonadherent','SYNTHETIC'])
  if not retained[i,k]:rows['events.tsv'].append([trial,id,(k+1)*30,'loss_to_followup','generated loss on grid','SYNTHETIC'])
 rows['observations.tsv'].append([trial,id,90,'response',y[i] if risk[i] else 'NA','NA' if risk[i] else 'lost_to_followup','NA','NA','SYNTHETIC','generated'])
for name in names:
 with (dest/name).open('w',newline='') as f:
  w=csv.writer(f,delimiter='\t',lineterminator='\n');w.writerow(headers[name]);w.writerows(rows[name])
(dest/'reference.json').write_text(json.dumps({'effect':float(estimate),'riskSetSizes':[int(v.sum()) for v in risk_at]},indent=2)+'\n');print('Independent multi-boundary dropout reference:',estimate,'risk sets:',[v.sum() for v in risk_at])
